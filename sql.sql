"""Policy Portal -- proposed PostgreSQL schema bootstrap (v1).

Run once or repeatedly with:
    pip install 'psycopg[binary]>=3.1'
    export DATABASE_URL='postgresql://...'
    python sql.py

- PostgreSQL 14+ compatible DDL (identity, JSONB, IF NOT EXISTS).
- Uses CREATE SCHEMA/TABLE/INDEX IF NOT EXISTS.
- Entire bootstrap runs in a single transaction; failure rolls it back.
- Does not DROP, truncate, or rewrite existing data.
- Re-running IS NOT a schema migration: IF NOT EXISTS does not validate or
  upgrade existing objects. Use Alembic or a migration system for upgrades.
- The proposed design is a starting point, not a production-final data model.
"""

from __future__ import annotations

import os
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from psycopg import Connection

SCHEMA_NAME = "policy_portal"

# Fixed SQL only: do not interpolate user input into these statements.
# Identifiers are schema-qualified so they do not depend on search_path.
DDL: tuple[str, ...] = (
    "CREATE SCHEMA IF NOT EXISTS policy_portal",

    # Stable policy identity. External IDs are scoped to CID, source, and type.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy (
        policy_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        cid text NOT NULL,
        source_system text NOT NULL DEFAULT 'crowdstrike',
        policy_type text NOT NULL,
        source_policy_id text NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT policy_natural_key UNIQUE
            (cid, source_system, policy_type, source_policy_id),
        CONSTRAINT policy_cid_not_empty CHECK (length(btrim(cid)) > 0),
        CONSTRAINT policy_source_id_not_empty CHECK (length(btrim(source_policy_id)) > 0)
    )
    """,

    # One linear revision sequence per stream (observed, baseline, draft).
    # Revision 1 must be a full snapshot. Later revisions can be snapshots
    # (checkpoints) or deltas, each pointing at its predecessor.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy_revision (
        revision_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        policy_pk bigint NOT NULL
            REFERENCES policy_portal.policy(policy_pk) ON DELETE RESTRICT,
        stream text NOT NULL,
        revision_no integer NOT NULL,
        previous_revision_no integer,
        storage_mode text NOT NULL,
        document jsonb,
        source_policy_version integer,
        policy_name text,
        policy_description text,
        platform text,
        source_created_by text,
        source_modified_by text,
        settings_hash text,
        canonical_hash text,
        source_created_at timestamptz,
        source_modified_at timestamptz,
        saved_at timestamptz NOT NULL DEFAULT now(),
        saved_by text NOT NULL,
        source text NOT NULL,
        CONSTRAINT policy_revision_identity UNIQUE (policy_pk, stream, revision_no),
        CONSTRAINT policy_revision_stream_check
            CHECK (stream IN ('observed', 'baseline', 'draft')),
        CONSTRAINT policy_revision_positive CHECK (revision_no > 0),
        CONSTRAINT policy_revision_storage_check CHECK (
            (storage_mode = 'snapshot'
                AND document IS NOT NULL AND jsonb_typeof(document) = 'object')
            OR (storage_mode = 'delta' AND document IS NULL)
        ),
        CONSTRAINT policy_revision_parent_check CHECK (
            (revision_no = 1 AND previous_revision_no IS NULL
                 AND storage_mode = 'snapshot')
            OR (revision_no > 1 AND previous_revision_no IS NOT NULL
                 AND previous_revision_no = revision_no - 1)
        ),
        CONSTRAINT policy_revision_previous_fk
            FOREIGN KEY (policy_pk, stream, previous_revision_no)
            REFERENCES policy_portal.policy_revision(policy_pk, stream, revision_no)
            ON DELETE RESTRICT
    )
    """,

    # Mutable operational state: changes here need not rewrite the large JSONB.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy_state (
        policy_pk bigint NOT NULL
            REFERENCES policy_portal.policy(policy_pk) ON DELETE RESTRICT,
        stream text NOT NULL,
        current_revision_no integer,
        is_active boolean NOT NULL DEFAULT true,
        is_disabled boolean NOT NULL DEFAULT false,
        baseline_status text,
        hosts_status text,
        last_observed_at timestamptz,
        updated_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT policy_state_pk PRIMARY KEY (policy_pk, stream),
        CONSTRAINT policy_state_stream_check
            CHECK (stream IN ('observed', 'baseline', 'draft')),
        CONSTRAINT policy_state_revision_fk
            FOREIGN KEY (policy_pk, stream, current_revision_no)
            REFERENCES policy_portal.policy_revision(policy_pk, stream, revision_no)
            ON DELETE RESTRICT
    )
    """,

    # Append-only ordered edits. SQL NULL means value absent; jsonb 'null'
    # means an explicit JSON null. Presence flags distinguish them.
    # One event may have several operations, ordered by operation_no.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy_revision_change (
        revision_pk bigint NOT NULL
            REFERENCES policy_portal.policy_revision(revision_pk) ON DELETE RESTRICT,
        operation_no integer NOT NULL,
        operation text NOT NULL,
        json_pointer text NOT NULL,
        setting_id text,
        old_present boolean NOT NULL,
        old_value jsonb,
        new_present boolean NOT NULL,
        new_value jsonb,
        CONSTRAINT policy_change_pk PRIMARY KEY (revision_pk, operation_no),
        CONSTRAINT policy_change_positive CHECK (operation_no > 0),
        CONSTRAINT policy_change_path_check CHECK (left(json_pointer, 1) = '/'),
        CONSTRAINT policy_change_old_presence_check CHECK (
            (old_present AND old_value IS NOT NULL)
            OR (NOT old_present AND old_value IS NULL)
        ),
        CONSTRAINT policy_change_new_presence_check CHECK (
            (new_present AND new_value IS NOT NULL)
            OR (NOT new_present AND new_value IS NULL)
        ),
        CONSTRAINT policy_change_semantics_check CHECK (
            (operation = 'add' AND new_present)
            OR (operation = 'remove' AND old_present AND NOT new_present)
            OR (operation = 'replace' AND old_present AND new_present)
        )
    )
    """,

    # Stable exclusion identity.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.exclusion (
        exclusion_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        cid text NOT NULL,
        source_system text NOT NULL DEFAULT 'crowdstrike',
        kind text NOT NULL,
        source_exclusion_id text NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT exclusion_natural_key UNIQUE
            (cid, source_system, kind, source_exclusion_id),
        CONSTRAINT exclusion_cid_not_empty CHECK (length(btrim(cid)) > 0),
        CONSTRAINT exclusion_source_id_not_empty
            CHECK (length(btrim(source_exclusion_id)) > 0)
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS policy_portal.exclusion_revision (
        revision_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        exclusion_pk bigint NOT NULL
            REFERENCES policy_portal.exclusion(exclusion_pk) ON DELETE RESTRICT,
        stream text NOT NULL,
        revision_no integer NOT NULL,
        previous_revision_no integer,
        storage_mode text NOT NULL,
        document jsonb,
        source_exclusion_version integer,
        exclusion_value text,
        applied_globally boolean,
        source_created_at timestamptz,
        source_modified_at timestamptz,
        source_created_by text,
        source_modified_by text,
        host_group_ids text[] NOT NULL DEFAULT ARRAY[]::text[],
        exclusion_hash text,
        canonical_hash text,
        saved_at timestamptz NOT NULL DEFAULT now(),
        saved_by text NOT NULL,
        source text NOT NULL,
        CONSTRAINT exclusion_revision_identity UNIQUE (exclusion_pk, stream, revision_no),
        CONSTRAINT exclusion_revision_stream_check
            CHECK (stream IN ('observed', 'baseline', 'draft')),
        CONSTRAINT exclusion_revision_positive CHECK (revision_no > 0),
        CONSTRAINT exclusion_revision_storage_check CHECK (
            (storage_mode = 'snapshot'
                AND document IS NOT NULL AND jsonb_typeof(document) = 'object')
            OR (storage_mode = 'delta' AND document IS NULL)
        ),
        CONSTRAINT exclusion_revision_parent_check CHECK (
            (revision_no = 1 AND previous_revision_no IS NULL
                 AND storage_mode = 'snapshot')
            OR (revision_no > 1 AND previous_revision_no IS NOT NULL
                 AND previous_revision_no = revision_no - 1)
        ),
        CONSTRAINT exclusion_revision_previous_fk
            FOREIGN KEY (exclusion_pk, stream, previous_revision_no)
            REFERENCES policy_portal.exclusion_revision(exclusion_pk, stream, revision_no)
            ON DELETE RESTRICT
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS policy_portal.exclusion_state (
        exclusion_pk bigint NOT NULL
            REFERENCES policy_portal.exclusion(exclusion_pk) ON DELETE RESTRICT,
        stream text NOT NULL,
        current_revision_no integer,
        is_active boolean NOT NULL DEFAULT true,
        baseline_status text,
        last_observed_at timestamptz,
        updated_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT exclusion_state_pk PRIMARY KEY (exclusion_pk, stream),
        CONSTRAINT exclusion_state_stream_check
            CHECK (stream IN ('observed', 'baseline', 'draft')),
        CONSTRAINT exclusion_state_revision_fk
            FOREIGN KEY (exclusion_pk, stream, current_revision_no)
            REFERENCES policy_portal.exclusion_revision(exclusion_pk, stream, revision_no)
            ON DELETE RESTRICT
    )
    """,

    """
    CREATE TABLE IF NOT EXISTS policy_portal.exclusion_revision_change (
        revision_pk bigint NOT NULL
            REFERENCES policy_portal.exclusion_revision(revision_pk) ON DELETE RESTRICT,
        operation_no integer NOT NULL,
        operation text NOT NULL,
        json_pointer text NOT NULL,
        old_present boolean NOT NULL,
        old_value jsonb,
        new_present boolean NOT NULL,
        new_value jsonb,
        CONSTRAINT exclusion_change_pk PRIMARY KEY (revision_pk, operation_no),
        CONSTRAINT exclusion_change_positive CHECK (operation_no > 0),
        CONSTRAINT exclusion_change_path_check CHECK (left(json_pointer, 1) = '/'),
        CONSTRAINT exclusion_change_old_presence_check CHECK (
            (old_present AND old_value IS NOT NULL)
            OR (NOT old_present AND old_value IS NULL)
        ),
        CONSTRAINT exclusion_change_new_presence_check CHECK (
            (new_present AND new_value IS NOT NULL)
            OR (NOT new_present AND new_value IS NULL)
        ),
        CONSTRAINT exclusion_change_semantics_check CHECK (
            (operation = 'add' AND new_present)
            OR (operation = 'remove' AND old_present AND NOT new_present)
            OR (operation = 'replace' AND old_present AND new_present)
        )
    )
    """,

    # Usage is a different lifecycle from policy configuration.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy_usage_snapshot (
        usage_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        policy_pk bigint NOT NULL
            REFERENCES policy_portal.policy(policy_pk) ON DELETE RESTRICT,
        observed_at timestamptz NOT NULL,
        saved_at timestamptz NOT NULL DEFAULT now(),
        status text NOT NULL,
        lookup_status text,
        reason text,
        member_count integer,
        resolved_host_count integer,
        applied_host_count integer,
        host_group_ids text[] NOT NULL DEFAULT ARRAY[]::text[],
        metrics jsonb NOT NULL DEFAULT '{}'::jsonb,
        source text NOT NULL DEFAULT 'crowdstrike_discover',
        CONSTRAINT usage_member_count_nonnegative
            CHECK (member_count IS NULL OR member_count >= 0),
        CONSTRAINT usage_resolved_host_count_nonnegative
            CHECK (resolved_host_count IS NULL OR resolved_host_count >= 0),
        CONSTRAINT usage_applied_host_count_nonnegative
            CHECK (applied_host_count IS NULL OR applied_host_count >= 0),
        CONSTRAINT usage_metrics_object CHECK (jsonb_typeof(metrics) = 'object')
    )
    """,

    # Optional detail for snapshots that include individual hosts.
    # Avoid placing huge host arrays in the immutable policy document.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.policy_usage_host (
        usage_pk bigint NOT NULL
            REFERENCES policy_portal.policy_usage_snapshot(usage_pk) ON DELETE RESTRICT,
        device_id text NOT NULL,
        hostname text,
        platform_name text,
        os_version text,
        last_seen timestamptz,
        assigned_source_policy_id text,
        applied boolean,
        applied_at timestamptz,
        details jsonb NOT NULL DEFAULT '{}'::jsonb,
        CONSTRAINT usage_host_pk PRIMARY KEY (usage_pk, device_id),
        CONSTRAINT usage_host_details_object CHECK (jsonb_typeof(details) = 'object')
    )
    """,

    # Simple audit events, intentionally independent of JSONB payload history.
    """
    CREATE TABLE IF NOT EXISTS policy_portal.audit_event (
        audit_pk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        entity_type text NOT NULL,
        entity_pk bigint,
        stream text,
        revision_no integer,
        action text NOT NULL,
        actor text,
        occurred_at timestamptz NOT NULL DEFAULT now(),
        details jsonb NOT NULL DEFAULT '{}'::jsonb,
        CONSTRAINT audit_details_object CHECK (jsonb_typeof(details) = 'object')
    )
    """,

    # Indexes reflect likely access paths, not speculative JSONB searches.
    # UNIQUE(..., stream, revision_no) already supplies a B-tree usable
    # for newest-revision lookups via a backward index scan.
    """
    CREATE INDEX IF NOT EXISTS ix_policy_revision_platform
      ON policy_portal.policy_revision(platform, saved_at DESC)
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_policy_state_active
      ON policy_portal.policy_state(stream, updated_at DESC)
      WHERE is_active = true
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_policy_change_setting
      ON policy_portal.policy_revision_change(setting_id, revision_pk)
      WHERE setting_id IS NOT NULL
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_exclusion_revision_host_groups
      ON policy_portal.exclusion_revision USING GIN(host_group_ids)
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_usage_recent
      ON policy_portal.policy_usage_snapshot(policy_pk, observed_at DESC)
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_usage_host_device
      ON policy_portal.policy_usage_host(device_id)
    """,
    """
    CREATE INDEX IF NOT EXISTS ix_audit_entity_time
      ON policy_portal.audit_event(entity_type, entity_pk, occurred_at DESC)
    """,
    # Intentionally no whole-document GIN index: add after profiling queries.
)


def apply_schema(conn: "Connection") -> None:
    """Apply the idempotent bootstrap DDL using the CALLER'S transaction.

    Call from ``with psycopg.connect(dsn) as conn: apply_schema(conn)``.
    The connection context commits on success and rolls back on error.
    If invoked on a long-lived connection, the caller must commit/rollback.
    Do not run schema installation during every Anvil request.
    """
    # Serialize concurrent bootstrap attempts; released on transaction end.
    conn.execute("SELECT pg_advisory_xact_lock(20261023, 1)")
    for statement in DDL:
        conn.execute(statement)


def main() -> None:
    try:
        import psycopg
    except ImportError as exc:
        raise SystemExit("Install Psycopg: pip install 'psycopg[binary]>=3.1'") from exc

    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        raise SystemExit("DATABASE_URL environment variable is required")

    # Context commits only after all CREATE statements succeed.
    with psycopg.connect(dsn, connect_timeout=10) as conn:
        apply_schema(conn)

    print("Policy Portal schema bootstrap completed (existing objects preserved).")
    print("Note: IF NOT EXISTS does not upgrade or validate older schemas.")


if __name__ == "__main__":
    main()
